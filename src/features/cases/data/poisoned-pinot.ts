// Helper to make a map from object for DialogueTreeDefinition nodes
function makeNodesMap(nodesObj: Record<string, unknown>): Map<string, DialogueNodeDefinition> {
  const map = new Map<string, DialogueNodeDefinition>();
  for (const [key, val] of Object.entries(nodesObj)) {
    map.set(key, val as DialogueNodeDefinition);
  }
  return map;
}

